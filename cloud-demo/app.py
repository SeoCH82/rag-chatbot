from __future__ import annotations

import os
from pathlib import Path
from urllib.parse import urlparse

import streamlit as st
from cloud_logic import answer_question, remote_model
from prompt_budget import PromptBudgetError

ROOT = Path(__file__).resolve().parent


def settings():
    def get(name):
        value = os.environ.get(name, "")
        if not value:
            try:
                value = st.secrets.get(name, "")
            except st.errors.StreamlitSecretNotFoundError:
                value = ""
        return value
    url, key = get("BACKEND_URL"), get("BACKEND_API_KEY")
    if urlparse(url).scheme != "https" or len(key) < 32:
        st.error("홈페이지의 서버 연결 설정이 필요합니다. 관리자에게 문의해 주세요.")
        st.stop()
    return url, key


@st.cache_resource(show_spinner=False)
def load_store():
    from langchain_community.vectorstores import FAISS
    from langchain_huggingface import HuggingFaceEmbeddings
    embeddings = HuggingFaceEmbeddings(
        model_name="jhgan/ko-sroberta-multitask", model_kwargs={"device": "cpu"},
        encode_kwargs={"normalize_embeddings": True},
    )
    # Only use the public index generated by our own bundle preparation script.
    return FAISS.load_local(str(ROOT / "faiss_index"), embeddings,
                            allow_dangerous_deserialization=True)


def main():
    st.set_page_config(page_title="개인 RAG 챗봇", page_icon="🔎")
    st.title("🔎 개인 RAG 챗봇")
    url, key = settings()
    if "messages" not in st.session_state:
        st.session_state.messages = []
    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            st.markdown(message["content"])
    question = st.chat_input("궁금한 내용을 질문하세요", max_chars=2000)
    if not question:
        return
    previous = next((m["content"] for m in reversed(st.session_state.messages)
                     if m["role"] == "assistant"), "")
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)
    with st.chat_message("assistant"):
        try:
            with st.spinner("답변을 생성하는 중입니다..."):
                answer = answer_question(question, previous, load_store, remote_model(url, key))
            st.markdown(answer)
        except PromptBudgetError as error:
            answer = str(error)
            st.warning(answer)
        except Exception:
            # Do not reveal ngrok, API credentials, tracebacks or private paths.
            answer = "답변 서버에 연결할 수 없습니다. 잠시 후 다시 시도해 주세요."
            st.error(answer)
    st.session_state.messages.append({"role": "assistant", "content": answer})


if __name__ == "__main__":
    main()
